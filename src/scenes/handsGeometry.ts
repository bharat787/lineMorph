const SCALE = 0.27
const BASELINE_Y = 286.2
function place(d: string): string {
  let isX = true
  return d.replace(/[MLC]|-?\d*\.?\d+/g, token => {
    if (/^[MLC]$/.test(token)) { isX = true; return token }
    const n = Number(token)
    const result = isX ? 700 + (n - 640) * SCALE : BASELINE_Y + (n - 400) * SCALE
    isX = !isX
    return result.toFixed(3)
  })
}

